/* ---------- 牌資料輔助 ---------- */

const SUIT_INFO = {
  '權杖': '火',
  '聖杯': '水',
  '寶劍': '風',
  '錢幣': '土',
}

const COURT_NAMES = ['侍者', '騎士', '皇后', '國王']

// 回傳牌的牌組、元素、身份
export const getCardInfo = (card) => {

  if (card.group === '大阿爾克那') {
    return { kind: 'major', suit: null, element: null, role: null }
  }

  const suit = card.group
  const element = SUIT_INFO[suit] || null
  const courtName = COURT_NAMES.find((name) =>
    card.name === `${suit}${name}`
  )

  if (courtName) {
    return { kind: 'court', suit, element, role: courtName }
  }

  return { kind: 'number', suit, element, role: card.name.slice(suit.length) }
}
